# Port CQC's VR hands and body into Blackout, verbatim. python3 tools/port_cqc.py <path to cqc/index.html>
# Writes src/cqc/port.js: CQC's code from `const HAND_DATA` (the skinned hand, its finger poses and grips) to the end
# of bodyArms (the procedural body: clothes, boots, belt, feet that step, legs and arms solved to your head and hands),
# with a shim header for the CQC game globals it reads (camera, rig, level, CONFIG.body, ...). Re-run after CQC
# changes; game/cqcbody.js drives it. Paths that need CQC's guns, props or rooms are never called here.
import re, sys
from pathlib import Path

src = Path(sys.argv[1]).read_text()
lines = src.split('\n')
def find(pat, start=0):
    for i in range(start, len(lines)):
        if re.match(pat, lines[i]): return i
    raise SystemExit('not found: ' + pat)
a = find(r'^const HAND_DATA = \{')
b = find(r'^function bodyHolster\(', a)
block = '\n'.join(lines[a:b])

def section(name, start):            # brace-matched `  name: {...}` inside CONFIG
    i = find(r'^  ' + name + r': \{', start)
    depth, out = 0, []
    for ln in lines[i:]:
        out.append(ln); depth += ln.count('{') - ln.count('}')
        if depth <= 0: break
    return '\n'.join(out).rstrip().rstrip(',')
cfg = find(r'^const CONFIG = \{')
body = section('body', cfg)
holdOffset = re.search(r'holdOffset:\s*(\[[^\]]*\])', src).group(1)
deskAim = re.search(r'deskAim:\s*(\{[^}]*\})', src)
deskAim = deskAim.group(1) if deskAim else '{}'
view_fit = re.search(r'^const VIEW_FIT = .*$', src, re.M).group(0)
slot_rot = re.search(r'^const SLOT_ROT = .*$', src, re.M).group(0)
hand_fit_i = find(r'^const HAND_FIT = \{')
depth, hf = 0, []
for ln in lines[hand_fit_i:]:
    hf.append(ln); depth += ln.count('{') - ln.count('}')
    if depth <= 0: break
hand_fit = '\n'.join(hf)

# every name the shim provides; cqcSet() replaces them at run time
SHIM = ['camera', 'renderer', 'scene', 'rig', 'level', 'comfort', 'vrHands', 'deskHand', 'stream', 'inv', 'JUMP', 'KICK', 'CONTACT',
        'headWorld', 'xrHeadOk', 'handPose', 'roomContaining', 'roomFloorAt', 'stairFloor', 'rLX', 'rLZ', 'rWX', 'gunOf', 'lhBusy',
        'gunBodyBoxes', 'vmLoad', 'vmPackWrist', 'wearApply', 'glove104Start', 'handsGloveShader', 'ownStep', 'underfoot', 'goreStep',
        'splashStep', 'bodyKickJump', 'maxAniso', 'audio', 'soundAt', 'nBurst', 'pulseSoft', 'mechPulse', 'vmhTake', 'vmhFrameStart', 'vmGun']
header = f"""// GENERATED by tools/port_cqc.py from CQC's index.html: CQC's VR hands and body, verbatim. Do not edit by hand.
/* eslint-disable */
import * as THREE from 'three';
import {{ RoundedBoxGeometry }} from 'three/addons/geometries/RoundedBoxGeometry.js';
const QS = location.search;
const clamp = (x, a = 0, b = 1) => (x < a ? a : x > b ? b : x);
const smoothstep = (a, b, x) => {{ const t = clamp((x - a) / (b - a)); return t * t * (3 - 2 * t); }};
const CONFIG = {{
{body},
  player: {{ eyeHeight: 1.7 }},
  weapons: {{ holdOffset: {holdOffset}, deskAim: {deskAim} }},
  polish: {{ audio: {{}} }},
}};
CONFIG.body.vmSleeves = false;                 // the procedural sleeves (the viewmodel pack's are not in this game)
{view_fit}
{slot_rot}
{hand_fit}
const HANDLOOK = {{ on: false, vmhScale: 1, procScale: 1, extra: 1 }}, WEAR = {{ gloves: true }}, GORE_ON = false, SPLASH = {{ on: false }}, WM = {{}};
const GROUP = {{}}, GUNPHYS = {{}}, ENEMY = {{}}, GC_WRAP = {{}}, FREEGRIP = {{}}, ATC = {{}}, VFG_SUP = {{}}, KNOCK_SND = {{}};
let {', '.join(n + ' = null' for n in SHIM)};
export function cqcSet(o) {{
{chr(10).join(f"  if ('{n}' in o) {n} = o.{n};" for n in SHIM)}
}}
"""
footer = """
export { HANDS, BODY, HAND_DATA, HPOSE, handsBuild, bodyBuild, bodyPre, bodyArms, setFinger, applyFingers, poseFromPad, poseCurl,
  poseFromGrip, padState, placeHand, freeFrame, bodyPrecompile };
"""
out = Path(__file__).resolve().parent.parent / 'src/cqc/port.js'
out.write_text(header + block + footer)
print(out, len(block) // 1024, 'KB of CQC code')
